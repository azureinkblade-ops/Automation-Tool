"""CPU/mock tests for I2V presentation adapter (9:16 FIT_INSIDE)."""
from __future__ import annotations

import hashlib
from pathlib import Path

import pytest

from tools.i2v_presentation_adapter import (
    DEFAULT_SOCIAL_HEIGHT,
    DEFAULT_SOCIAL_WIDTH,
    PRESENTATION_TRANSFORM_ID,
    SVD_NATIVE_HEIGHT,
    SVD_NATIVE_WIDTH,
    VIDEO_CREATES_IDENTITY_CANON,
    I2VPresentationAdapter,
    PresentationJobStore,
    PresentationValidation,
    RawSvdClipRef,
    compute_fit_inside_letterbox_9x16,
    mock_render,
    sha256_bytes,
)


@pytest.fixture
def store(tmp_path):
    return PresentationJobStore(tmp_path / "pres_store")


def _clip(tmp_path, payload: bytes = b"raw-svd-clip-bytes") -> RawSvdClipRef:
    path = tmp_path / "raw_svd.mp4"
    path.write_bytes(payload)
    return RawSvdClipRef(
        video_path=str(path),
        video_sha256=sha256_bytes(payload),
        source_image_sha256=sha256_bytes(b"source-still"),
    )


def test_transform_fit_inside_no_crop_stretch():
    t = compute_fit_inside_letterbox_9x16()
    assert t.transform_id == PRESENTATION_TRANSFORM_ID
    assert t.source_width == SVD_NATIVE_WIDTH
    assert t.source_height == SVD_NATIVE_HEIGHT
    assert t.target_width == DEFAULT_SOCIAL_WIDTH
    assert t.target_height == DEFAULT_SOCIAL_HEIGHT
    assert t.content_width + t.pad_left + t.pad_right == t.target_width
    assert t.content_height + t.pad_top + t.pad_bottom == t.target_height
    # FIT_INSIDE: content aspect matches source aspect within 1px rounding
    src_aspect = SVD_NATIVE_WIDTH / SVD_NATIVE_HEIGHT
    content_aspect = t.content_width / t.content_height
    assert abs(src_aspect - content_aspect) < 0.02
    # no upscale beyond fit: content fits inside target
    assert t.content_width <= t.target_width
    assert t.content_height <= t.target_height
    # for landscape into portrait, expect vertical pads dominate
    assert t.pad_top + t.pad_bottom > t.pad_left + t.pad_right


def test_present_pass_and_canon_no(store, tmp_path):
    adapter = I2VPresentationAdapter(store=store, render=mock_render, output_dir=tmp_path / "out")
    result = adapter.present_video(_clip(tmp_path), workflow_id="wf-pres-1")
    assert result.validation_status == PresentationValidation.PASS.value
    assert result.video_creates_identity_canon is False
    assert VIDEO_CREATES_IDENTITY_CANON is False
    assert result.presented_width == 1080
    assert result.presented_height == 1920
    assert result.presented_video_sha256
    assert Path(result.presented_video_path).is_file()


def test_source_hash_mismatch_fails_closed(store, tmp_path):
    clip = _clip(tmp_path)
    clip.video_sha256 = "0" * 64
    adapter = I2VPresentationAdapter(store=store, render=mock_render, output_dir=tmp_path / "out")
    result = adapter.present_video(clip, workflow_id="wf-hash-bad")
    assert result.validation_status == PresentationValidation.SOURCE_HASH_MISMATCH.value
    assert result.presented_video_sha256 is None


def test_ready_reuse_requires_matching_hash(store, tmp_path):
    adapter = I2VPresentationAdapter(store=store, render=mock_render, output_dir=tmp_path / "out")
    clip = _clip(tmp_path)
    first = adapter.present_video(clip, workflow_id="wf-reuse")
    second = adapter.present_video(clip, workflow_id="wf-reuse")
    assert second.reused_existing is True
    assert second.presentation_job_id == first.presentation_job_id
    # corrupt presented artifact
    Path(first.presented_video_path).write_bytes(b"CORRUPTED")
    third = adapter.present_video(clip, workflow_id="wf-reuse")
    assert third.reused_existing is False
    assert third.validation_status == PresentationValidation.PASS.value
    # mock render is deterministic — regenerated bytes rematch first hash, but must not silent-reuse corrupt file
    assert Path(third.presented_video_path).read_bytes() != b"CORRUPTED"
    assert store.verify_ready_artifact(store.get_by_idempotency(third.presentation_idempotency_key))


def test_idempotency_binds_source_video_sha(store, tmp_path):
    adapter = I2VPresentationAdapter(store=store, render=mock_render, output_dir=tmp_path / "out")
    a = adapter.present_video(_clip(tmp_path, b"clip-a"), workflow_id="wf-same")
    b = adapter.present_video(_clip(tmp_path, b"clip-b"), workflow_id="wf-same")
    assert a.presentation_idempotency_key != b.presentation_idempotency_key
    assert a.presentation_job_id != b.presentation_job_id
